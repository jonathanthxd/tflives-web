/**
 * Accepts a single Unicode emoji grapheme (including flags, modifiers and ZWJ
 * sequences) while rejecting arbitrary strings/HTML. This lets the server
 * support the complete in-app catalogue without maintaining a tiny allowlist.
 */
const UNICODE_EMOJI_REACTION = /^(?:\p{Regional_Indicator}{2}|[#*0-9]\uFE0F?\u20E3|\p{Extended_Pictographic}(?:\uFE0F|\uFE0E)?(?:\p{Emoji_Modifier})?(?:\u200D\p{Extended_Pictographic}(?:\uFE0F|\uFE0E)?(?:\p{Emoji_Modifier})?)*)$/u;

export function isUnicodeEmojiReaction(value: unknown): value is string {
  return typeof value === "string" && value.length <= 32 && UNICODE_EMOJI_REACTION.test(value);
}
